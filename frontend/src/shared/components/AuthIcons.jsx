/**
 * Trả về icon phù hợp theo id thiết bị
 */
export function getDeviceIcon(deviceId) {
  switch (deviceId) {
    case 'smart-door-lock':
      return <DeviceLockIcon />;
    case 'smart-speaker':
      return <DeviceSpeakerIcon />;
    case 'window-sensor':
      return <DeviceWindowIcon />;
    case 'smart-plug':
      return <DevicePlugIcon />;
    case 'environment-sensor':
      return <DeviceSensorIcon />;
    default:
      return <DeviceLockIcon />;
  }
}

